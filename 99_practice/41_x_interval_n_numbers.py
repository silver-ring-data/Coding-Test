# x만큼 간격이 있는 n개의 숫자 (Lv.1)
# https://school.programmers.co.kr/learn/courses/30/lessons/12954


# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(x, n):
    """
    1. 리스트의 길이는 n
    2. 각 요소의 값은 x * (index+1)
    """
    return [x*(index + 1) for index in range(n)]


# --- 피드백 과정 ---
#
# 1. 접근은 바로 나왔다 — 길이는 n, i번째 값은 x * (i+1).
#
# 2. 막힌 건 문법이었다. `for index in n` 으로 썼는데 n은 정수라 반복할 수 없다.
#    "N번 반복" 은 range(n) 이 기본형이다.
#
# 3. range(n) 은 0부터 시작하니 식에 +1 보정이 붙었다.
#    코드에 남은 +1 은 대개 시작점을 안 맞췄다는 신호다.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(x, n):
    """x부터 시작해 x씩 증가하는 숫자 n개를 리스트로 리턴한다."""
    # range(1, n + 1) -> 1, 2, ..., n
    # 시작점을 1로 옮겨 식에서 +1 보정을 없앴다.
    return [x * i for i in range(1, n + 1)]


# --- 설명 ---
#
# 1. range(1, n + 1) 로 시작점을 옮기면 보정이 사라진다.
#    변수명도 index 보다 i 가 낫다 — 인덱스가 아니라 몇 번째 배수인지를 뜻하므로.
#
# 2. 시간 O(n) / 공간 O(n). 원소 n개를 만들어 리턴하는 문제라 더 줄일 수 없다.
#
# 다시 만나면: range 는 0부터. 1부터 필요하면 보정하지 말고 시작점을 옮긴다.
