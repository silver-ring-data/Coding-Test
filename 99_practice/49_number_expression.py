# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    '''
    1부터 차례대로 더해서
        1. n이면 갯수 + 1
        2. n보다 커지면 다음 수부터 차례대로 더함
    '''
    answer = 0
    current_sum = 0
    index = 1
    while index <= n:
        for num in range(index, n + 1):
            current_sum += num
            if current_sum == n:
                answer += 1
                index += 1
                current_sum = 0
                break
            elif current_sum > n:
                index += 1
                current_sum = 0
                break
    return answer


# --- 피드백 과정 ---
#
# 1. 접근은 처음부터 맞았다 — 시작점을 1, 2, 3, … 으로 옮기며 넘칠 때까지 누적. 세션은 코드를 주지 않고
#    질문만 했다.
# 2. 첫 코드의 걸린 곳 넷 — ① `while index > n` (1 > 15 라 루프에 들어가지도 않음)
#    ② 안쪽 `range(1, n)` 이 시작점을 무시하고 항상 1부터 더함 → `range(index, …)`
#    ③ `current_sum` 을 시작점이 바뀔 때 0 으로 안 되돌림 → 두 번째 시작점부터 넘친 채로 시작
#    ④ 시작점을 바꾸려면 안쪽 for 를 빠져나와야 하는데 `continue` 를 씀 → `break`.
# 3. 둘째 판에서 남은 셋 — `current_sum` 초기화 위치 · `== n` 뒤에도 for 를 계속 돌리던 것(손해) ·
#    `range(index, n)` 이 n 을 빼서 n 하나짜리 표현을 못 세고 while 이 무한 루프. 손으로 n=15 를 따라가며 찾았다.
# 4. "시작점을 어디까지?" 는 힌트(8+9=17) 뒤에 본인이 **n/2** 를 짚었다.
# 5. 복잡도는 본인 결정으로 코테 공부에서 다루지 않기로 (규칙 1️⃣ 에 반영, 2026-09-10). 아래 설명에 세션이 한 줄만.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(n):
    """n 을 연속한 자연수의 합으로 나타내는 방법의 수.

    시작점이 n/2 를 넘으면 두 항만 더해도 n 을 넘으므로, n 하나짜리(1) 외에는 1..n//2 만 본다.
    """
    answer = 1                       # n 하나짜리
    for start in range(1, n // 2 + 1):
        total = 0
        for num in range(start, n):
            total += num
            if total == n:
                answer += 1
                break
            if total > n:
                break
    return answer


# --- 설명 ---
#
# 1. 시작점은 `n // 2` 까지만 — 그 뒤는 `start + (start+1) > n` 이라 볼 게 없다. n 자체는 `answer = 1` 로 미리.
# 2. `index += 1; current_sum = 0` 이 두 갈래에 중복되던 것을 — for 를 빠져나오면 항상 하는 일이라 —
#    `total = 0` 을 for 앞에 두고 시작점 증가는 바깥 for 에 맡겼다. while + 수동 index 가 for 하나로.
# 3. 복잡도 — 시작점 start 에서 넘칠 때까지 약 n/start 개를 더하므로 합은 n(1 + 1/2 + … + 1/(n/2)) ≈ **O(n log n)**.
#    공간 O(1).
# 4. **짧지만 안 되는 대안 — `sum(range(start, end))` 를 end 를 늘려 가며 매번 부르기.** 매 단계 O(k) 라
#    누적합보다 훨씬 느리다. 한 번 더하고 끝내는 게 맞다.
# 5. 더 빠른 길 (참고): 연속 k 개의 합이 n 이려면 n − k(k−1)/2 가 k 로 나눠떨어져야 한다. k 를 1부터
#    k(k+1)/2 ≤ n 까지만 돌면 O(√n). 다음에 다시 만나면 이쪽을 떠올려 볼 것.
#
