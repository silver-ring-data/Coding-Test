# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    ways = [1,2]
    
    if n == 1:
        return 1
    
    for i in range(2,n):
        ways.append(ways[i-1]+ways[i-2])
    answer = ways[-1] % 1234567

    return answer


# --- 피드백 과정 ---
#
# 접근: n=1~4 를 손으로 세서 1, 2, 3, 5 → "5 = 2+3" 을 본인이 찾음.
#   처음엔 결과(숫자가 맞는다)만 답했고,
#   "4칸 직전 마지막 점프" 를 물으니 3번째 칸 · 2번째 칸을 본인이 짚음 → 원인까지 연결.
# 피보나치 수(56)와 같은 모양이라는 것, 재귀 대신 리스트에 쌓는 것은 본인이 떠올림.
# 루프 경계: 인덱스를 한 칸 밀어(ways[0]=1칸) range(2, n) 으로 끝을 맞춤. 이번엔 안 꼬였다.
# 반례: n=1 → ways=[1,2], 루프 0번, ways[-1]=2 (답은 1).
#   세션이 "n=1 을 손으로 따라가 봐" 만 묻고, 버그는 본인이 찾아 if 로 막음.
# 걸린 지점: % 를 중간에 해도 되는 이유를 모름 ("잘 모르겠어").
#   피보나치 수(56) 메모에 이미 있던 내용 → 일의 자리(÷10) 예시로 다시 설명.
# 결과: 통과.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(n):
    """n칸을 1칸·2칸으로 가는 방법 수를 1234567로 나눈 나머지를 반환한다.

    마지막 점프가 1칸이면 n-1칸, 2칸이면 n-2칸에서 온다.
    직전 두 값만 들고 앞으로 가며, 더할 때마다 나머지로 줄인다.
    """
    a, b = 1, 1          # 0칸, 1칸
    for _ in range(n - 1):
        a, b = b, (a + b) % 1234567
    return b


# --- 설명 ---
#
# 고친 이유
# - 0칸=1 부터 시작하면 n=1 이 루프 0번으로 자연스럽게 1 이 나와 if 가 필요 없다.
# - 매번 % 1234567: 일의 자리끼리 더해도 일의 자리 결과는 같다 (÷10 예시).
#   (a+b) % m == (a%m + b%m) % m. 파이썬 int 는 무한이라 통과했지만,
#   n=2000 이면 400자리가 넘고 C++·Java 였으면 오버플로.
# - 리스트 대신 변수 두 개: 다음 칸에 필요한 건 직전 두 칸뿐.
# 복잡도: 시간 O(n), 공간 O(1).
# 짧지만 안 되는 대안: 재귀 f(n-1)+f(n-2) — 같은 값을 반복 계산하고 재귀 깊이 한도에 걸린다.
#
