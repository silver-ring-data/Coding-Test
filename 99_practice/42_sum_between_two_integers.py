# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(a, b):
    """
    1. a부터 1씩 더해서 b까지 있는 리스트 생성
    2. 리스트의 모든 합을 리턴
    """
    if a < b:
        comp_list = [comp for comp in range(a, b + 1)]
    else:
        comp_list = [comp for comp in range(b, a + 1)]
    answer = sum(comp_list)
    return answer


# --- 피드백 과정 ---
#
# 1. 접근은 맞았다 — a부터 b까지 늘어놓고 더한다.
#    처음 쓴 range(a, b) 가 세 케이스에서 0/7 을 냈고, 거기서 두 가지가 드러났다.
#
# 2. range 는 끝을 포함하지 않는다 → b + 1.
#    어제(41번)의 "range 는 0부터" 와 같은 뿌리다. range 의 양 끝은 늘 확인할 것.
#
# 3. "a와 b의 대소관계는 정해져있지 않습니다" 가 진짜 함정이었다.
#    a > b 면 range 가 빈 채로 돌아 합이 0 이 된다.
#    a == b 는 else 로 들어가 range(a, a+1) = [a] 가 되므로 따로 처리할 필요가 없었다.
#
# 4. 제한 조건의 한 줄이 코드 한 줄을 강제한다 —
#    조건을 먼저 읽고 각 줄이 코드의 어디에 대응하는지 짚고 시작하는 편이 낫다.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(a, b):
    """
    등차수열 합 공식으로 a~b 사이 정수의 합을 한 번에 구한다.
    (첫 + 끝) * 개수 // 2 — 대소관계가 정해져 있지 않아 min/max 로 양 끝을 잡는다.
    """
    min_num = min(a, b)
    max_num = max(a, b)
    count = max_num - min_num + 1
    return (min_num + max_num) * count // 2


# --- 설명 ---
#
# 1. min / max 로 양 끝을 뽑으면 if/else 분기가 통째로 사라진다.
#    "둘 중 작은 쪽부터 큰 쪽까지" 라는 말이 그대로 코드가 된다.
#
# 2. [comp for comp in range(...)] 는 꺼낸 값을 그대로 담기만 하는 복사였다.
#    sum 은 리스트가 아니라 하나씩 꺼낼 수 있는 것이면 받으므로 sum(range(...)) 로 족하다.
#    range 는 원소를 만들어 두지 않고 그때그때 계산한다 → 공간 O(n) → O(1).
#
# 3. 공식이 2로 나뉘는 이유 (여기서 한참 막혔다):
#        S = 3 + 4 + 5
#        S = 5 + 4 + 3      순서만 뒤집어 한 벌 더 쓴다
#       2S = 8 + 8 + 8      세로로 짝지으면 모든 칸이 (첫 + 끝) 로 같아진다
#       2S = (첫 + 끝) * 개수
#    곱셈으로 묶으려고 일부러 두 벌을 만들었으니, 2는 내가 복사한 횟수다.
#    개수는 max - min + 1 (양 끝 포함).
#
# 4. / 가 아니라 // 인 이유는 몫이 필요해서가 아니다.
#    (첫 + 끝) * 개수 는 항상 짝수라 어차피 나눠떨어진다. / 는 12.0 이라는 실수를 돌려주는데,
#    정수의 합에 실수가 나오면 맞지 않고 큰 수에서는 오차도 생긴다.
#
# 5. 시간 O(n) → O(1), 공간 O(1). 입력 크기와 무관하게 곱셈 한 번, 나눗셈 한 번이다.
#    -10,000,000 ~ 10,000,000 기준 sum(range(...)) 216ms vs 이 식 0.00036ms.
#    랜덤 20만 건을 sum(range(...)) 와 대조해 전부 일치함을 확인했다.
#
# 6. 짧지만 안 되는 대안: return sum(range(a, b + 1))
#    훨씬 짧지만 a=5, b=3 에서 0 을 낸다. 대소관계가 없다는 조건이 min/max 를 강제한다.
#
