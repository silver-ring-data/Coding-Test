# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(s):
    """
    공백으로 분리
    첫문자 탐색
    첫문자가 문자면 대문자로 바꿈
    """
    words = s.split(' ')
    result = []
    for word in words:
        if word == "":
            result.append(word)
        elif word[0].isalpha():
            result.append(word[0].upper() + word[1:].lower())
        else:
            result.append(word[0] + word[1:].lower())
    return " ".join(result)


# --- 피드백 과정 ---
#
# ※ 시간이 없어 **본인이 적은 논리(위 docstring)를 세션이 코드로 옮겼다.**
#    접근까지는 본인이 갔고, 손으로 완성한 코드는 아니다. 다시 만나면 직접 쓸 것.
#
# 1. 접근 자체는 맞았다 — 공백으로 쪼개고 / 각 조각의 첫 글자를 보고 / 문자면 올린다.
#    처음 초안은 여기서 네 군데가 걸렸다.
# 2. `if index == 0` 으로 첫 단어만 특별 취급했다. 모든 단어가 같은 처리를 받으므로
#    enumerate 도 index 도 필요 없다. **"첫 문자" 와 "첫 단어" 가 머릿속에서 섞였다.**
# 3. **`type(word[index]) == str` 로 문자/숫자를 가르려 했다 — 파이썬에서 항상 True 다.**
#    C 의 char 같은 문자 타입이 없어서 "3" 도 "a" 도 전부 str 이다. 길이 1 짜리 str 일 뿐.
#    타입이 아니라 **값의 성질을 묻는 메서드**(str.isalpha) 로 갈라야 한다.
#    덧붙여 word[index] 의 index 는 단어 목록의 번호라 글자 위치와도 무관했다 (word[0] 이라야 한다).
# 4. `s.split()` 을 썼다. 인자 없는 split 은 연속 공백을 하나로 뭉치고 앞뒤 공백을 버린다.
#    제한사항에 **"공백문자가 연속해서 나올 수 있다"** 가 있으므로 `split(' ')` 이라야
#    빈 문자열 조각이 남아 " ".join 으로 되붙일 때 공백 개수가 보존된다.
#    "a  b".split() -> ['a','b'] / "a  b".split(' ') -> ['a','','b']
# 5. 반환값이 answer 가 아니라 words 였다 (오타).
# 6. **나머지를 소문자로 내리는 것을 안 챙겼다.** 입출력 예 1 의 "unFollowed" 가 반례다.
#    첫 글자만 올리면 "UnFollowed" 가 되어 가운데 F 가 남는다. `word[1:].lower()` 가 한 세트.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(s):
    """각 단어를 첫 글자만 대문자, 나머지는 소문자로 바꿔 반환한다.

    split(' ') 로 공백을 그대로 살려 쪼개고, 각 조각을 [첫 글자] + [나머지] 로 잘라
    앞은 올리고 뒤는 내린 뒤 같은 공백으로 되붙인다. 빈 조각(연속 공백)도 그대로 통과한다.
    """
    return " ".join(w[:1].upper() + w[1:].lower() for w in s.split(' '))


# --- 설명 ---
#
# 1. `w[0]` 이 아니라 **`w[:1]` (슬라이싱)** 으로 바꾼 것이 핵심이다. 인덱싱은 빈 문자열에서
#    IndexError 지만 슬라이싱은 "" 를 돌려준다. 연속 공백이 만든 빈 조각을 따로 거를 필요가
#    없어져 1번의 `if word == ""` 가 통째로 사라진다.
# 2. **isalpha 분기도 필요 없다.** "3".upper() 는 "3" 이다 — 숫자에 upper 를 걸어도 그대로다.
#    "첫 글자가 문자일 때만 올린다" 와 "무조건 올린다" 의 결과가 같으므로 조건이 지워진다.
#    (다만 1번에서 isalpha 를 쓴 것은 틀린 게 아니라 의도를 드러낸 것이다. 지우려면
#     "숫자에 upper 를 걸어도 안전하다" 를 알고 지워야지, 몰라서 안 쓴 것과는 다르다.)
# 3. 시간 O(n), 공간 O(n) — 문자열이 불변이라 새로 만드는 비용은 어느 풀이든 같다.
#    줄어든 것은 복잡도가 아니라 **분기 개수**(3갈래 -> 0갈래)다.
# 4. **짧지만 안 되는 대안 — `return s.title()`.**
#    "3people unFollowed me".title() -> "3People Unfollowed Me" 로 3 뒤의 p 가 대문자가 된다.
#    title() 은 **알파벳이 아닌 문자 다음을 새 단어의 시작으로** 보기 때문이다.
#    제한사항의 "숫자는 단어의 첫 글자로만 나온다" 가 이 한 방을 막으려고 적힌 줄이다.
#    같은 이유로 아포스트로피에서도 깨진다: "don't".title() -> "Don'T".
# 5. 또 하나 안 되는 대안 — `" ".join(w.capitalize() for w in s.split())`.
#    capitalize 자체는 맞게 동작하지만(첫 글자 올리고 나머지 내림) **split 에 인자가 없어**
#    "a  b" 가 "A B" 로 공백이 하나 줄어든다. 틀린 곳이 단어 처리가 아니라 쪼개기라 눈에 안 띈다.
#
