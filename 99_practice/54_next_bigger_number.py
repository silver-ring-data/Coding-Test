# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    answer = n+1
    
    n_count_one = bin(n).count('1')
    
    while True:
        ans_count_one = bin(answer).count('1')
        if n_count_one == ans_count_one:
            return answer
        else:
            answer += 1
    return answer


# --- 피드백 과정 ---
#
# 접근: n+1부터 하나씩 늘려가며 2진수 1의 개수가 n과 같아지는 첫 수를 찾는다.
# bin(n).count('1')로 1의 개수를 세는 건 스스로 알고 있었음.
# 막힌 지점: while 조건을 어떻게 걸지 못 정해서 처음엔 `while :` 로 비워둠.
# 그다음 `ans_count_one`을 반복문 시작 전에 한 번만 계산해 둬서, answer가 바뀌어도
# 비교 대상이 그대로인 버그로 이어질 뻔했다 — 힌트를 받고서 반복문 안에서
# 매번 다시 계산하도록 스스로 고쳤다.
# 반례는 못 만들었지만, "n부터 시작하면 왜 안 되는가"(조건 1: n보다 커야 함)는
# 질문에 바로 답함.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(n):
    """n의 2진수 표현에서 1의 개수를 유지하며 n보다 큰 가장 작은 수를 반환한다.

    n+1부터 하나씩 늘리며 popcount(1의 개수)가 n과 같아지는 첫 수를 찾는다.
    while 조건에 "아직 같지 않다"를 직접 걸어, 매 반복마다 answer의 popcount를
    다시 계산하도록 만들었다(원래 풀이에서 이 재계산 누락이 버그 지점이었다).
    """
    n_count_one = bin(n).count('1')
    answer = n + 1
    while bin(answer).count('1') != n_count_one:
        answer += 1
    return answer


# --- 설명 ---
#
# `while True: / if-else: / 도달 안 하는 return`을 조건문 하나로 줄였다 —
# "popcount가 같아질 때까지 늘린다"는 의도가 while 조건에 그대로 드러난다.
# 시간복잡도: n ≤ 1,000,000 범위에서 다음 수까지 거리가 크지 않아 선형 탐색으로
# 충분하지만, 이론적 최악은 O(gap · log n)(gap = 다음 수까지 거리, count('1')가 O(log n)).
# 짧지만 안 되는 대안: answer를 n으로 시작하는 것 — n 자신은 조건 1("n보다 큰
# 자연수")을 애초에 만족하지 못해 탈락해야 하는데, n부터 비교를 시작하면 이 조건을
# 놓치게 된다.
#
# 다시 만나면: "다음 ~한 수를 찾아라" 류는 조건을 while에 직접 걸면
# if-else보다 의도가 더 잘 드러난다. 더 빠르게 하려면 popcount를 유지한 채
# 다음 수를 O(1)에 구하는 비트 트릭(최하위 1비트를 올리고 나머지 1들을
# 오른쪽으로 몰아주는 방식)도 있다 — 필요하면 그때 찾아본다.
