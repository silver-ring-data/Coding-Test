# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(A, B):
    '''
    작은수 * 큰수의 조합으로 곱한 것을 모두 더한 것이 최소임
    고로, A배열 B배열 각각 작은 순, 큰 순으로 나열후 모두 더함
    '''
    A.sort()
    B.sort()
    B.reverse()

    return sum(map(lambda a, b: a * b, A, B))


# --- 피드백 과정 ---
#
# 1. 접근은 처음부터 맞았다 — "작은 수엔 큰 수를 붙인다". 다만 처음 계획은 (A 오름·B 내림) 과
#    (A 내림·B 오름) 두 합을 구해 작은 쪽을 고르는 것이었는데, 둘은 **같은 짝의 순서만 뒤집은 것**이라
#    합이 같다. 비교가 필요 없고 정렬 한 방향이면 끝.
# 2. "왜 작은×큰이 최소인가" 를 "큰수끼리 곱하면 엄청 커지니까" 로 답했다 — 결과다. 원인은
#    A=[1,2], B=[3,4] 에서 1·3+2·4 − (1·4+2·3) = (2−1)(4−3) = 1, 즉 **큰 쪽끼리 묶으면 차이×차이만큼
#    손해**가 난다는 것. 원인 → 결과 축(시작메모)이 오늘도 나왔다.
# 3. 첫 코드는 `B.reverse()` 만 썼다. reverse 는 정렬이 아니라 **현재 순서를 뒤집기만** 한다 —
#    B=[4,5,4] 는 뒤집어도 [4,5,4]. 문제 예제(B=[5,4,4])는 우연히 통과해서 티가 안 났다.
#    반례를 주니 `B.sort(); B.reverse()` 로 고쳤다.
# 4. `sum(list(map(...)))` 의 `list()` 는 불필요 — sum 은 이터레이터를 바로 받는다. 어제의 map 소진 건은
#    오늘은 해당 없음(한 번만 소비).
# 5. 복잡도는 본인이 스킵 → 아래 설명에 적음.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(A, B):
    """A 오름차순 · B 내림차순으로 짝지어 곱의 합을 반환한다.

    큰 쪽끼리 묶으면 (a2-a1)(b2-b1) 만큼 손해이므로, 반대로 묶는 것이 최소다.
    """
    A.sort()
    B.sort(reverse=True)
    return sum(a * b for a, b in zip(A, B))


# --- 설명 ---
#
# 1. `B.sort(); B.reverse()` → `B.sort(reverse=True)` 한 줄. 새 리스트가 필요하면 `sorted(B, reverse=True)`.
# 2. `map(lambda a, b: a*b, A, B)` → `zip` 제너레이터. lambda 호출 비용이 없고 의도가 바로 읽힌다.
# 3. 복잡도 — 정렬 두 번 O(n log n) + 순회 O(n) = **O(n log n)**. 제자리 정렬이라 추가 공간 O(1)
#    (인자 리스트를 바꾼다는 점은 의식할 것 — 원본을 지켜야 하면 sorted 로).
# 4. **짧지만 안 되는 대안 — `sum(a*b for a, b in zip(sorted(A), reversed(B)))`.**
#    `reversed` 도 `reverse()` 와 같이 뒤집기만 한다. 내림차순은 `sorted(B, reverse=True)` 뿐.
# 5. 정당성 한 줄 (면접용): 어떤 짝짓기든 A 작은 것에 B 작은 것이 붙어 있으면, 그 둘을 서로 바꿔
#    합을 줄일 수 있다 → 바꿀 게 없는 상태 = 정렬 반대 방향. 전형적인 **교환 논법(exchange argument)**.
#
# 다시 만나면: reverse/reversed 는 뒤집기, 정렬은 sort/sorted 뿐. "왜 최소냐" 는 두 짝을 바꿨을 때
# 차이(차이×차이)로 답한다 — "커지니까" 는 결과.
