# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    """
    1부터 n까지 나머지가 0이면 약수
    이것들을 모두 더함
    """
    answer = 0
    for index in range(1, n + 1):
        if n % index == 0:
            answer = answer + index
    return answer


# --- 피드백 과정 ---
#
# 1. 접근 — 정의 그대로 1부터 n 까지 훑으며 나누어떨어지면 더했다. 통과한다.
#    n 이 자기 자신의 약수이므로 range 상한을 n+1 로 둔 것도 정확했다. O(n).
# 2. 본인이 먼저 "다 서칭하는 것을 효율적으로 만드는 방법이 있겠지?" 를 물었다.
#    금요일(44번)에 O(n) → O(√n) 을 한 직후라 그 감이 남아 있었다.
#    다만 44번과 줄이는 이유가 다르다 — 거기는 답 하나만 찾으면 되니 탐색을 끊었고,
#    여기는 약수를 전부 써야 하는데도 절반만 돈다. 근거가 "짝" 이라는 점이 핵심.
# 3. 약수의 짝(1·12 / 2·6 / 3·4)에서 두 수를 곱하면 n 이라는 것은 바로 봤다.
#    → index 가 약수면 n // index 도 약수라 한 번에 둘을 얻는다.
# 4. 갈린 지점 — n=16 의 함정을 "약수 개수가 홀수라 자기 자신을 한 번 더 곱해야 한다" 로 답했다.
#    관찰(개수가 홀수)은 맞았으나 세 군데가 어긋났다.
#    · 합을 구하는 문제인데 "곱한다" 고 말했다.
#    · "16 이 홀수" 가 아니라 "16 의 약수 개수가 홀수" 다. 주어를 붙여야 안 헷갈린다.
#    · 방향이 뒤집혔다. 4 를 한 번 더 더해야 하는 게 아니라, 4 의 짝이 4 자신이라
#      index 와 n // index 를 둘 다 더하면 두 번 들어간다. 빠지는 게 아니라 겹친다.
# 5. **원인 → 결과 축을 또 한 칸 못 내려갔다.** "약수 개수가 홀수" 는 관측된 결과고,
#    원인은 "n 이 완전제곱수라 √n 이 정수" 다. 어떤 n 에서 그렇게 되냐고 다시 물었을 때
#    답하지 못해 12(√≈3.464)와 16(√=4)을 나란히 놓고서야 풀렸다.
#    이론공부 쪽에서 나흘째 걸리고 있는 그 축과 같은 모양이다.
# 6. 시간이 없어 **최적화는 코드로 옮기지 못하고 개념까지만 갔다.** 아래 2번은 그 자리에서
#    쓴 것이 아니라 정리해 넣은 것이다 — 다시 만나면 직접 써 볼 것.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
from math import isqrt


def solution(n):
    """n 의 모든 약수의 합을 반환한다.

    약수는 곱해서 n 이 되는 짝으로 묶이고(index x (n // index) = n), 두 수가 모두
    sqrt(n) 보다 클 수는 없다. 그래서 sqrt(n) 까지만 훑어도 작은 쪽을 전부 만나고,
    큰 쪽은 n // index 로 공짜로 따라온다. n 이 완전제곱수일 때만 짝의 두 수가
    같아지므로(index x index = n) 그 한 번을 중복해서 더하지 않도록 막는다.
    """
    answer = 0
    for index in range(1, isqrt(n) + 1):
        if n % index == 0:
            pair = n // index
            answer += index if index == pair else index + pair
    return answer


# --- 설명 ---
#
# 1. O(n) → O(√n), 공간은 둘 다 O(1). n <= 3000 이라 원래 풀이로도 통과하지만,
#    같은 짝짓기가 소인수분해·약수 개수·완전수 판정에 그대로 쓰인다.
# 2. `+ 1` 은 44번에서 갈렸던 그 자리다. isqrt(16) = 4 인데 4 도 약수이므로
#    range(1, 4) 로 쓰면 4 를 놓친다. 완전제곱수에서만 티가 나서 더 위험하다.
# 3. `index == pair` 검사가 완전제곱수 처리 전부다. n=16 에서 index=4 일 때
#    pair 도 4 라 4 를 한 번만 더한다. 없으면 16 의 답이 31 대신 35 가 된다.
# 4. n=0 도 안전하다. isqrt(0) = 0 이라 range(1, 1) 이 비어 0 을 반환한다.
#    원래 풀이도 range(1, 1) 로 같은 값을 낸다.
# 5. int(n ** 0.5) 말고 math.isqrt — 정수 연산이라 부동소수점 오차가 없다. 44번과 같다.
# 6. 짧지만 안 되는 대안 — `sum(i for i in range(1, n+1) if n % i == 0)` 은 한 줄이고
#    읽기도 좋지만 상한이 n 그대로라 O(n) 이다. 줄여야 할 것은 글자 수가 아니라 탐색 범위다.
#    반대로 `sum(set(...))` 으로 중복을 없애는 건 되긴 하나, 겹치는 이유(완전제곱수)를
#    가려버려서 다음에 같은 함정을 또 밟는다.
#
