# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    '''
    n에서 거꾸로 0까지 내려간다
        1. 짝수면 //2 (순간이동 되돌리기, 건전지 0)
        2. 홀수면 -1 후 //2 (점프 되돌리기, 건전지 1)
    '''
    ans = 0
    current_loc = n
    while current_loc > 0:
        current_loc, extra = current_loc//2, current_loc%2
        if extra == 0:
            continue
        else:
            ans += 1
    return ans


# --- 피드백 과정 ---
#
# 1. 문제 자체가 감이 안 왔다 — "왜 5000 이 5 인가". 세션이 N=5 수직선 그림(점프 +1 = 1개, ×2 = 0개)을
#    그려 주고 "홀수는 ×2 로 못 만든다 → 마지막 걸음은 반드시 점프" 를 짚은 뒤 거꾸로 세기(5000→2500→…→625 홀수)로
#    감이 왔다. 그 뒤 "5000 에서 /2 를 계속하면 되겠네" 는 본인이 냈고 코드도 본인이 썼다.
# 2. 첫 코드의 걸린 곳 셋 — ① `while current_loc == 0` (조건 반대, 루프 진입 못 함 — 어제와 같은 패턴)
#    ② `current_loc, extra = current_loc%2, current_loc//2` 몫·나머지가 서로 바뀜
#    ③ 짝수 +1 / 홀수 +2 로 셈 — 건전지는 점프 1개·순간이동 0개뿐이라 2개짜리 동작은 없다.
#    ①②는 지적 한 번에 고쳤고 ③은 "모르겠어" → 거꾸로 가기를 앞으로 가기로 번역해 주니(÷2 = 순간이동 0개,
#    −1 = 점프 1개) 고쳤다. 홀수의 `//2` 가 −1 과 ÷2 두 단계를 합친 것이라 1개만 세면 된다는 것도 이때.
# 3. 다 푼 뒤 — `if extra == 0: continue` 는 아래에 건너뛸 게 없어 무의미(틀린 건 아님). `divmod` 는 몰랐다.
# 4. `bin(n).count('1')` 은 "이런 게 있다" 정도로만 — 아래 설명 4.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(n):
    """N 까지 가는 데 필요한 최소 건전지 수.

    N 에서 0 으로 거꾸로: 짝수면 절반으로(순간이동 되돌리기, 0개), 홀수면 1 빼고 절반으로(점프 되돌리기, 1개).
    홀수를 만난 횟수가 답이다.
    """
    answer = 0
    while n > 0:
        n, r = divmod(n, 2)
        answer += r                  # r 은 0 또는 1 — 홀수일 때만 +1
    return answer


# --- 설명 ---
#
# 1. 거꾸로 가면 선택이 없어진다 — 앞으로 갈 땐 매 위치에서 "점프냐 순간이동이냐" 를 골라야 하지만,
#    거꾸로 갈 땐 짝수는 ÷2 뿐이고 홀수는 −1 뿐이다 (홀수는 ×2 의 결과일 수 없으므로). 그래서 그리디가 성립.
# 2. `divmod(n, 2)` = `(n // 2, n % 2)`. 나머지가 0/1 이므로 if 없이 `answer += r` 로 바로 더한다.
#    변수도 `current_loc` 없이 n 을 직접 줄여도 된다 (함수 인자는 지역 변수).
# 3. 복잡도 — 매번 절반이 되므로 O(log n). n ≤ 10억이면 약 30번.
# 4. **더 짧은 대안 — `bin(n).count('1')`.** 위 루프가 하는 일이 정확히 "2로 나누며 나머지 적기" = 2진수 변환이고,
#    홀수를 센 것 = 2진수의 1 개수. 5000 = 0b1001110001000 → 1 이 5개. 맞는 풀이지만 왜 되는지 모르고 쓰면
#    면접에서 설명을 못 하니, 루프 버전을 먼저 쓸 수 있어야 한다.
# 5. **짧지만 안 되는 대안 — 앞으로 가며 "가능하면 ×2, 아니면 +1".** 0 에서 ×2 는 0 이라 시작부터 막히고,
#    N=5 에서 2→4→5 가 최적인지 2→3→… 인지를 앞에서는 알 수 없다. 방향을 뒤집어야 선택이 사라진다.
#
