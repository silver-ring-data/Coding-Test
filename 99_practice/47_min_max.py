# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(s):
    '''
    공백으로 나눈 문자열로 저장
    s를 탐색해
    값이 작으면 최소값으로 저장
    값이 크면 최대값으로 저장
    '''
    nums = s.split(" ")
    min_num = int(nums[0])
    max_num = int(nums[0])
    for num in nums:
        num = int(num)
        if num > max_num:
            max_num = num
        if num < min_num:
            min_num = num
    answer = " ".join(map(str, [min_num, max_num]))
    return answer


# --- 피드백 과정 ---
#
# 1. 접근은 처음부터 맞았다 — 쪼개고, 한 번 훑으면서 최소·최대를 갱신. 초기값을 0 이 아니라
#    첫 원소로 잡은 것도 좋았다 (0 으로 잡으면 전부 음수인 입력 "-1 -2" 에서 최대가 0 이 된다).
# 2. answer 를 만들어 놓고 `return min_num` 을 했다 (오타). 07 일의 `return words` 와 같은 종류.
# 3. `elif` → `if`. 최대 갱신과 최소 갱신은 서로 배타적인 분기가 아니라 **독립된 두 질문**이라
#    if 둘이 정직한 표현이다. 다만 이 문제에선 elif 로도 결과가 같았다 — 첫 원소로 초기화했으니
#    첫 원소는 둘 다 안 걸리고, 그 뒤 원소는 최댓값보다 크면서 동시에 최솟값보다 작을 수 없다.
# 4. `int(num)` 을 원소마다 세 번 부르고 있었다 → 루프 첫 줄에서 `num = int(num)` 한 번으로.
#    고친 뒤에도 `max_num = int(num)` 에 int 가 하나 남아 있었다 — 이미 정수인 것을 또 감싼 것.
# 5. 짧게 줄이려다 **이터레이터 소진**에 걸렸다:
#        nums = map(int, s.split()); min(nums); max(nums)
#    map 은 리스트가 아니라 한 번만 소비되는 이터레이터라, min 이 다 먹고 나면 max 는 빈 것을 받아
#    ValueError. 그다음 판은 `min(map(int, s.split()))` / `max(map(int, s.split()))` 로 map 을 두 번
#    만들었는데 — 통과는 하지만 split 두 번·int 변환 두 번이라 list 로 한 번 만드는 것보다 일이 많다.
#    → 2번 판이 결론.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(s):
    """공백으로 구분된 정수 문자열에서 "최소 최대" 를 반환한다.

    한 번에 정수 리스트로 바꿔 두고 내장 min/max 를 쓴다. 두 번 순회하지만 읽기 쉽다.
    """
    nums = list(map(int, s.split()))
    return f"{min(nums)} {max(nums)}"


# --- 설명 ---
#
# 1. 두 판의 차이는 복잡도가 아니라 **순회 횟수와 메모리**다.
#    - 1번(한 번 순회, 추가 메모리 O(1)) : 입력이 스트림이거나 한 번만 읽을 수 있을 때 맞는 모양.
#    - 2번(두 번 순회, 리스트 O(n))     : 이 문제 규모(짧은 문자열)면 차이 없고 의도가 바로 읽힌다.
#    둘 다 시간 O(n). 어차피 `s.split()` 이 리스트를 만드는 순간 O(n) 메모리라, 이터레이터로
#    버티려는 시도는 이득이 없었다.
# 2. **`s.split(" ")` 보다 `s.split()` 이 안전하다.** 인자 없는 split 은 연속 공백을 뭉치고 앞뒤 공백을
#    버려서 `int("")` 로 터질 여지가 없다. 07 일 JadenCase 는 공백 개수를 **보존해야** 해서 `split(' ')`
#    이 맞았고, 오늘은 공백이 구분자일 뿐이라 반대다 — **같은 함수를 문제가 뭘 요구하느냐로 고른다.**
# 3. `" ".join(map(str, [a, b]))` 는 f-string 한 줄로 충분하다. join 은 원소가 여럿·가변일 때 쓰는 도구.
# 4. **짧지만 안 되는 대안 — `min(s.split())` / `max(s.split())` 로 문자열째 비교.**
#    "10" < "9" 가 True 다 (사전순). 음수도 "-1" 과 "-10" 이 뒤집힌다. 반드시 int 로 바꾼 뒤 비교.
# 5. 또 하나 — `sorted(nums)[0]`, `sorted(nums)[-1]`. 맞긴 하지만 O(n log n). 양끝만 필요할 때
#    정렬은 과하다.
#
# 다시 만나면: map/filter/generator 는 **한 번 쓰면 비는 이터레이터**다 — 두 번 쓸 거면 list 로 받아 둔다.
# 최소·최대 초기값은 0 이 아니라 첫 원소. 그리고 최대·최소 갱신처럼 독립된 조건은 elif 가 아니라 if 둘.
