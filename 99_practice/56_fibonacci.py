# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    func = [0,1]
    for index in range(2, n+1):
        func.append(func[index-1]+func[index-2])
    
    answer = func[n] % 1234567
    return answer


# --- 피드백 과정 ---
#
# 접근: 점화식을 보고 재귀(자기 호출)로 가려 했다.
# 막힌 지점 ①: 종료 조건 없이 재귀만 씀 → 끝없이 호출.
#   고친 뒤에도 `if num <= 0:` 안에 재귀를 넣어 조건이 반대로 걸렸다.
#   (while 조건 반대 · n^2 배열 자르기 if 방향과 같은 모양)
# 막힌 지점 ②: `// 1234567` 로 몫을 구함. 나머지는 `%`.
# 막힌 지점 ③: 재귀가 왜 느린지 감이 안 왔다.
#   f(5) 트리에서 f(3) 2번 · f(2) 3번 중복 계산을 같이 셈.
#   "아래에서 위로 쌓기"도 처음엔 이해 못 했고,
#   리스트 인덱스로 F(2)=fib[1]+fib[0] 을 직접 보여준 뒤
#   fib[i-1]+fib[i-2] 를 본인이 코드로 옮겼다.
#   "앞서 계산한 걸 배열에 저장해 두는 것" 은 본인이 정리함 (DP 첫 맛보기).
# 결과: 통과. 단 13·14번이 458MB · 327ms (아래 설명 참고).


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(n):
    """n번째 피보나치 수를 1234567로 나눈 나머지를 반환한다.

    직전 두 값만 들고 앞으로 가며, 더할 때마다 나머지로 줄인다.
    """
    a, b = 0, 1
    for _ in range(n):
        a, b = b, (a + b) % 1234567
    return a


# --- 설명 ---
#
# 고친 이유
# - 매번 % 1234567: (a+b) % m == (a%m + b%m) % m 이라 답은 같다.
#   안 줄이면 F(100000) 은 2만 자리가 넘어 메모리 458MB 까지 감.
#   파이썬이라 통과했지, C++·Java 였으면 오버플로로 오답.
# - 리스트 대신 변수 두 개: 다음 칸에 필요한 건 직전 두 칸뿐.
# 복잡도: 시간 O(n), 공간 O(1).
# 짧지만 안 되는 대안: 재귀 f(n-1)+f(n-2)
#   같은 값을 계속 다시 구해 호출 수가 지수로 늘고, 재귀 깊이 한도(약 1000)에도 걸린다.
#
