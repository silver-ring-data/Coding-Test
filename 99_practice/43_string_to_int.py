# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(s):
    """
    1. 첫자리 부호인지 확인
    2. 부호 제외 s의 길이를 확인 -> 몇자리 수인지 확인
    3. 각 순서별로 10^(길이-index-1)곱하기
    """
    s_len = len(s)
    answer = 0
    if s[0] == '+':
        s_len = s_len - 1
        for index, num in enumerate(s):
            if index == 0:
                continue
            answer = answer + int(num) * (10 ** (s_len - index))
    elif s[0] == '-':
        s_len = s_len - 1
        for index, num in enumerate(s):
            if index == 0:
                continue
            answer = answer - int(num) * (10 ** (s_len - index))
    else:
        for index, num in enumerate(s):
            answer = answer + int(num) * (10 ** (s_len - index - 1))

    return answer


# --- 피드백 과정 ---
#
# 1. 접근은 처음부터 맞았다 — 부호를 떼고, 남은 자리마다 10의 거듭제곱을 곱해 더한다.
#    자리값(place value)을 손으로 계산하는 정석적인 방식이다.
#
# 2. 첫 식이 10 ** (길이 - index) 였다. "23" 의 index 0 에서 10**2 = 100 이 나와
#    2 가 200 이 됐다. 0-based 인덱스에서 맨 앞 자리의 지수는 (길이 - 1) 이므로 -1 이 필요했다.
#    41·42번의 range 양 끝 문제와 같은 뿌리다 — 0부터 세는 것과 개수를 세는 것의 차이.
#
# 3. || 를 썼다. 파이썬은 or / and 다.
#
# 4. 부호 분기에서 for 가 여전히 s 전체를 돌아 첫 바퀴에 int('-') 를 하게 돼 있었다.
#    → ValueError. 부호를 확인한 것과 부호를 건너뛰는 것은 별개의 일이다.
#
# 5. 부호를 판정만 하고 결과에 반영하지 않아 "-12" 가 12 로 나왔다.
#    조건을 확인하는 코드와 그 조건을 쓰는 코드가 떨어져 있으면 이 누락이 잘 생긴다.
#
# 6. 고친 뒤 지수를 (s_len - index) 로 두어 통과했다. 맞긴 하지만 우연처럼 보인다.
#    부호가 있을 때 index 가 1칸 밀리는 것을, s_len 에서 1을 빼 상쇄한 것이다.
#    두 개의 -1 이 서로 지워진 형태라 나중에 읽으면 왜 맞는지 알기 어렵다.
#
# 7. int('2') 를 빠뜨려도 파이썬은 에러를 내지 않는다 — '2' * 3 은 '222' 다.
#    조용히 틀린 값이 나오는 쪽이라 더 위험하다.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(s):
    """문자열을 정수로 바꿔 반환한다.

    int() 가 "부호(선택) + 숫자" 형태를 그대로 받으므로 자리값 계산이 필요 없다.
    """
    return int(s)


# --- 설명 ---
#
# 1. 문제의 제한 조건("부호와 숫자로만 구성", "잘못된 값은 입력되지 않는다")이
#    사실상 int() 가 받아들이는 형태를 그대로 서술한 것이었다.
#        int("-1234") -> -1234
#        int("+1234") ->  1234
#        int("  -12 ") ->  -12   (양끝 공백도 무시한다)
#    부호는 되지만 소수점·쉼표는 안 된다 — int("12.5"), int("1,234") 는 둘 다 ValueError.
#    "int 는 숫자만 받는다" 고 알고 있었는데 경계선은 소수점이지 부호가 아니었다.
#
# 2. 중간 단계로 분기를 먼저 없애 봤다. 달라지는 것이 「어디부터 읽나」와 「부호가 뭔가」
#    둘뿐이므로, 그 둘을 변수로 뽑으면 for 가 하나로 줄고 6번의 지수 상쇄도 사라진다.
#        sign = -1 if s[0] == '-' else 1
#        digits = s[1:] if s[0] in '+-' else s
#        ... 10 ** (len(digits) - index - 1) ... 마지막에 sign 을 곱한다
#    s[0] in '+-' 는 or 두 번보다 "둘 중 하나에 속하는가" 라는 뜻이 그대로 읽힌다.
#    이 버전은 자리값 계산을 손으로 해야 하는 문제(진법 변환 등)에서 그대로 쓸 수 있다.
#
# 3. 거듭제곱 없이도 된다 (호너의 방법). 왼쪽부터 읽으며 answer = answer * 10 + 숫자.
#    "123" 이면 0 -> 1 -> 12 -> 123. 자릿수를 셀 필요가 아예 없어져 -1 실수도 없어진다.
#
# 4. 복잡도는 시간 O(n), 공간은 나의 풀이가 O(n)·int(s) 가 O(1) 이다 (n = s 의 길이).
#    시간이 같은 이유는 int() 도 결국 글자를 하나씩 다 읽어야 값이 정해지기 때문이다 —
#    마지막 글자를 안 보고 "1234" 의 값을 알 수는 없다. 공간이 갈리는 곳은 s[1:] 로,
#    잘라낸 새 문자열을 복사해 둔다. 다만 n <= 5 라 실제 차이는 없다.
#    그러므로 int(s) 를 고르는 이유는 성능이 아니라, 위 4·5·6번의 실수를 할 여지가
#    아예 없다는 것이다. 복잡도가 같으면 짧고 읽기 쉬운 쪽을 고른다.
#
# 5. 짧지만 안 되는 대안:
#    - float(s)          : -1234.0 이 나온다. 값은 맞지만 요구된 타입이 정수가 아니다.
#    - eval(s)           : 동작은 하지만 임의 코드 실행이라 입력을 믿을 수 없는 곳에서는 금기다.
#    - int(s.strip('+-')): strip 이 부호를 지워 "-12" 가 12 가 된다.
#                          양수 케이스만 시험하면 통과한 것처럼 보여 특히 위험하다.
#
