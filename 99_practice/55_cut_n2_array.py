# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n, left, right):
    '''
    인덱스 x가 있으면 n으로 나눈 몫과 나머지로 행, 열을 구한다.
    행과 열 중 규칙대로 값을 고른다.
    left부터 right까지의 인덱스에 대해 반복해서 값들을 모은다.
    '''
    answer = []
    for x in range(left,right+1):
        row, col = x//n+1, x%n+1
        if row >= col:
            answer.append(row)
        else:
            answer.append(col)
    
    return answer


# --- 피드백 과정 ---
#
# 접근: 처음엔 0으로 채운 n×n 표를 만들어 "0이면 채우고 아니면 건너뛴다"로 가려 했다.
# 예시 영상을 보다가 스스로 규칙을 찾았다 — 1234 / 2234 / 3334 / 4444,
# "k행은 k가 k번, 그다음은 순서대로". 설명대로 채우지 않고 결과에서 규칙을 뽑아낸 게 핵심.
# 막힌 지점 ①: 규칙 문장("i행 i열까지 영역을 i로 채운다")에서 1행 2열과 2행 1열이
#   어떻게 되는지 헷갈렸다 — "빈 칸만 채운다"를 놓침. 둘 다 2.
# 막힌 지점 ②: 인덱스 5(0번부터)를 "2행 1열"로 셌다. 1차원 배열의 0번이 1행 1열인데
#   한 칸 밀려 셈 — 값(2)은 맞았지만 위치는 4번 것. 몫·나머지(0부터)에 +1 해서
#   행·열을 얻는 건 스스로 해냄.
# 막힌 지점 ③: 개념 → 코드 번역은 막힘 없이 넘어갔으나 `if row <= col: append(row)` 로
#   조건 방향이 반대로 들어갔다 (이러면 큰 쪽이 아니라 작은 쪽이 들어간다).
#   말로는 "열이 행보다 작거나 같으면 행"이라 정확히 말했는데 코드에서 뒤집힘.
#   n=3, left=2, right=5 (정답 [3,2,2,3]) 의 x=2 를 손으로 따라가서 직접 `>=` 로 고침.
#   09/10·09/11 while 조건 반대와 같은 모양 — 조건 방향은 예시 한 칸을 손으로 돌려 확인.
# 반례는 "예시 한 칸 직접 따라가기"로 갈렸다.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(n, left, right):
    """1차원으로 편 n×n 표에서 left~right 구간의 값을 반환한다.

    표를 만들지 않고, 인덱스 x 의 (행, 열) = (x // n, x % n) 에서 값이
    max(행, 열) + 1 임을 이용해 필요한 구간만 계산한다.
    """
    return [max(x // n, x % n) + 1 for x in range(left, right + 1)]


# --- 설명 ---
#
# 고친 이유: if/else 로 큰 쪽을 고르던 것이 곧 max 이고, 몫·나머지가 0부터라
# +1 을 두 번 하던 것을 max 뒤에 한 번만 하도록 옮겼다. 동작은 같은 축약이다.
# (max 로 쓰면 이번에 겪은 조건 방향 뒤집힘 실수가 생기기 어렵다.)
# 시간복잡도: O(right - left + 1), 공간복잡도: 결과 리스트 크기와 같다.
# 짧지만 안 되는 대안: n×n 표를 통째로 만든 뒤 펴서 [left:right+1] 로 자르기 —
# 코드는 짧지만 칸이 n² 개라 n 이 크면 메모리·시간이 감당되지 않는다.
# 필요한 구간(right - left 가 작다)만 계산하는 게 이 문제의 요점.
#
# 다시 만나면: "표를 만들어 자르라" 류는 표를 만들지 말고, 인덱스 → (행, 열) → 값의
# 식을 먼저 찾는다. 규칙은 설명 문장보다 작은 n 의 결과를 직접 써보면 보인다.
