# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(n):
    x = 0
    for index in range(1, n):
        x = x + 1
        if n % x == 1:
            return x


# --- 피드백 과정 ---
#
# 1. 접근 — 조건이 문제에 그대로 적혀 있으니 x 를 1부터 올리며 처음 걸리는 값을 반환했다.
#    통과한다. 최악(n=999984)도 0.075초. n 이 홀수면 x=2 에서 즉시 끝나 루프가 길어지는
#    경우 자체가 드물기 때문인데, 이걸 모르고 그냥 통과했다.
# 2. index 와 x 가 똑같이 1,2,3... 을 센다. range 에 시작값을 주면 둘 다 없어진다.
# 3. `n % x == 1` 을 `x 는 n-1 의 약수` 로 이항하는 것을 못 떠올렸다. 이게 핵심이었다.
# 4. 용어 착오 — 약수(divisor)를 "최소공약수" 라고 답했다. 없는 말이다.
#    최대공약수·최소공배수는 대상이 둘 이상일 때 쓰고("공"=공통), 공약수의 최소는
#    언제나 1 이라 물어볼 값이 아니다. 여기는 대상이 n-1 하나뿐이다.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
import math


def solution(n):
    """n % x == 1 을 만족하는 가장 작은 x 를 반환한다.

    n % x == 1 은 n-1 = qx 와 같으므로 x 는 n-1 의 약수다. 약수는 곱해서 n-1 이
    되는 짝으로 묶이고 두 수가 모두 sqrt(n-1) 보다 클 수는 없으니, 가장 작은
    약수는 항상 sqrt(n-1) 이하에 있다. 못 찾으면 n-1 이 소수라는 뜻이다.
    """
    for x in range(2, math.isqrt(n - 1) + 1):
        if n % x == 1:
            return x
    return n - 1


# --- 설명 ---
#
# 1. 조건식은 문제 문장 그대로 두고 탐색 상한만 n → sqrt(n) 으로 내렸다.
#    O(n) → O(√n), 공간은 둘 다 O(1). 실측 0.075초 → 0.000052초 (n=999984).
# 2. `+1` 이 없으면 제곱수에서 답을 놓친다. n=10 은 n-1=9, isqrt(9)=3 인데 답도 3 이라
#    경계 위에 있다. 빼먹으면 9 를 반환하는데 10 % 9 == 1 이라 틀린 티가 안 난다.
# 3. int((n-1) ** 0.5) 대신 math.isqrt — 이 범위(≤10^6)에선 결과가 같지만 정수 계산이라
#    부동소수점 오차가 없다. 인자도 isqrt(n) 이 아니라 isqrt(n-1) 이라야 이유가 설명된다.
# 4. 짧지만 안 되는 대안 — `next(x for x in range(2, n) if n % x == 1)` 은 한 줄이지만
#    상한이 n 그대로라 O(n) 이다. 줄여야 할 것은 글자 수가 아니라 탐색 범위였다.
#
