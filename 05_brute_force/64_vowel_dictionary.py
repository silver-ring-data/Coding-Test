# --------------------------------------------------------------------------
# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(word):
    vowel = {
        "A":0, 
        "E":1,
        "I":2,
        "O":3,
        "U":4
        }
    weight = [781, 156, 31, 6, 1]
    answer = 0
    for i, part in enumerate(word):
        index = vowel[part]
        answer += index*weight[i]+1
    return answer


# --- 피드백 과정 ---
#
# 전체 단어 수를 본인이 바로 셈: 5 + 5^2 + ... + 5^5 = 3905. 다 만들어도 되는 크기.
# 세션은 DFS 로 사전을 다 만드는 쪽을 제안했지만, 본인은 처음부터 직접 계산을 원함.
#   "순서를 해야 하니 결국 다 만들어야 하나?" → 순서는 모음 번호(A=0~U=4)가 대신한다.
# "I" = 1563 으로 첫째 자리 덩어리 781 (= 5^0+...+5^4) 을 같이 셈.
#   첫째 자리 식(모음 번호 × (5^0+...+5^4))은 본인이 짚음.
#   둘째 자리부터 수식으로 옮기는 데서 막힘 → AA 로 시작하는 단어 수(156)를 세어 보고
#   자리별 덩어리 크기를 표로 박아 둠: [781, 156, 31, 6, 1].
# 1판: weight[vowel[part]] → 모음 번호로 덩어리를 고름. "I" 가 31.
# 2판: 곱하기·+1 은 넣었지만 여전히 weight[모음 번호]. "I" 가 63.
#   자리(weight 고르기)와 모음 번호(곱하기)는 역할이 다르다 → enumerate 로 둘 다 꺼냄.
# 3판 통과. H-Index 때처럼 "자리 번호를 코드로 옮기기"에서 또 걸림.
# 검산 반례: "UUUUU" = 3905 (사전 맨 끝 = 전체 단어 수).


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(word):
    """자리마다 (모음 번호 × 그 자리 덩어리 크기 + 1) 을 더한다."""
    weights = [781, 156, 31, 6, 1]   # 자리 i 뒤에 붙는 꼬리 0~(4-i) 글자 수의 합
    return sum('AEIOU'.index(c) * weights[i] + 1 for i, c in enumerate(word))


# --- 설명 ---
#
# 자리 i 의 글자를 한 칸 뒤 모음으로 바꾸면, 그 사이에
# "지금 접두사로 시작하는 단어 전부"(덩어리)를 건너뛴다. +1 은 자기 자신.
# dict 대신 'AEIOU'.index 로 모음 번호. weights 는 sum(5**j for j in range(5-i)) 로도 계산 가능.
# 복잡도: O(len(word)) = 최대 5번.
# 다른 방법: DFS 로 3905개 사전을 순서대로 만들고 words.index(word) + 1.
#   붙이기 → 기록 → 더 들어가기 순서, 길이 5면 멈춤. 느리지만 규칙을 못 찾아도 풀린다.
# 짧지만 안 되는 대안: weight[모음 번호] — 덩어리 크기는 자리로 정해진다 (1·2판).
#
# 다시 만나면: 사전 순 위치 = 자리별 (번호 × 하위 트리 크기 + 1) 의 합.
