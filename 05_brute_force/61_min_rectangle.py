# 1. 나의 풀이
# --------------------------------------------------------------------------
def solution(sizes):
    '''
    가로세로를 긴걸 앞에 짧은걸 뒤에 배치
    가로 및 세로 최댓값 계산
    곱한값 리턴
    '''
    small =0
    big = 0
    for size in sizes:
        
        small_size, big_size = min(size), max(size)
        if small < small_size:
            small = small_size
        if big < big_size:
            big = big_size
    answer = small*big
    return answer


# --- 피드백 과정 ---
#
# 접근: 명함마다 긴 변/짧은 변으로 정리 → 각각 최댓값 → 곱. 처음부터 맞음.
# "왜 최소?" → "긴 것끼리, 짧은 것끼리 모아야 낭비가 없다" 고 답함.
#   세션이 원인 쪽으로 다듬음: 지갑 변은 어차피 각 최댓값 이상이어야 하고, 이 곱이 그 하한.
# 반례: 회전 없는 max(가로)*max(세로) 는 문제 예시 2 가 이미 반례라고 본인이 짚음.
# 코드 1판: sizes.sort(key=lambda x: x[0]) 로 "긴 걸 앞에" 를 하려 함.
#   → 바깥 리스트(명함 순서)만 바뀌고 명함 안 가로·세로는 그대로. 계획과 코드가 어긋남.
#   [8, 15] 를 따라가게 하니 막혀서 "어떻게 바꾸지" → min/max 힌트 뒤 본인이 for 안으로 옮김.
# 결과: 통과.


# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(sizes):
    """모든 명함이 들어가는 최소 지갑 넓이를 반환한다.

    명함마다 긴 변·짧은 변으로 정리하고, 긴 변 최댓값 × 짧은 변 최댓값.
    """
    return max(max(s) for s in sizes) * max(min(s) for s in sizes)


# --- 설명 ---
#
# 고친 이유
# - 최댓값 갱신 루프를 max + 제너레이터로 접음. 로직은 같다.
# 복잡도: O(n).
# 짧지만 안 되는 대안
# - sizes.sort(...): 명함 순서만 바꾼다. 명함 안을 바꾸려면 원소마다 min/max (또는 sorted(s)).
# - max(가로) * max(세로): 회전을 안 써서 예시 2 에서 틀림.
# - 전체 최댓값 × 전체 최솟값: 짧은 변은 "명함별 짧은 변의 최댓값" 이어야 한다.
