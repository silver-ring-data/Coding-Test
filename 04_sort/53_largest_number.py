from functools import cmp_to_key


def solution(numbers):
    '''
    가장 큰 수는 앞자리가 클수록 앞에 오도록 하면 됨

    sorted(리스트, key=cmp_to_key(compare))
    ''.join(map(str,[a,b]
    '''
    def compare(a, b):
        type_1 = ''.join(map(str, [a, b]))
        type_2 = ''.join(map(str, [b, a]))

        if type_1 > type_2:
            return -1
        elif type_1 < type_2:
            return 1
        else:
            return 0

    answer = ''.join(map(str, sorted(numbers, key=cmp_to_key(compare))))
    if answer[0] == str(0):
        return str(0)
    return answer


# --- 피드백 과정 ---
#
# 접근은 "앞자리가 클수록 앞에 온다" 로 시작했다. 방향은 맞았지만 3 과 30 처럼
# 첫 자리가 같은 경우에서 막혔다 — "두 번째 자리를 비교하면 된다" 고 했는데
# 3 은 두 번째 자리가 아예 없어서 정의가 안 됐다. 거기서 "자리를 하나씩 비교"
# 하는 대신 "둘을 이어붙인 결과를 통째로 비교" 하는 쪽으로 규칙을 바꿨고,
# 그게 곧 정답 규칙이었다 (a+b 와 b+a 중 큰 쪽).
#
# 걸린 곳 셋.
# ① **규칙은 찾았는데 코드로 옮기는 단계에서 멈췄다.** cmp_to_key 사용 예시를
#    보여주자 예시의 비교 규칙(일의 자리, a % 10)을 그대로 가져다 쓰고 본인 규칙을
#    넣지 않았다. 09/15 H-Index 에서 "정렬 후 순위 ≤ 인용수" 를 enumerate 로 옮기지
#    못한 것과 **같은 패턴 (개념 → 코드 번역)** 이다. 두 번째 확인.
# ② **문제 예시가 우연히 통과해서 틀린 걸 못 봤다.** 일의 자리 비교로도
#    [3,30,34,5,9] → "9534330", [6,10,2] → "6210" 이 그대로 나온다.
#    반례 [12,21](→"1221", 정답 "2112") · [45,5](→"455", 정답 "545") 를 만들어
#    보여준 뒤에야 갈린 지점이 보였다. **예시 통과 = 정답 아님.**
# ③ 타입 — numbers 가 정수 리스트라 ''.join 에서 TypeError (map(str, ...) 로 해결),
#    그리고 answer[0] == 0 은 문자 '0' 과 정수 0 비교라 항상 False.
#
# 엣지케이스(원소가 전부 0)는 세션이 [0,0,0] → "000" 을 짚어 주자 본인이 바로
# "0 으로 리턴해야겠지" 라고 답했고, 첫 글자만 보면 된다는 것도 힌트 한 줄로 냈다.
#
#
# --------------------------------------------------------------------------
# 2. 최적화된 버전
# --------------------------------------------------------------------------
def solution(numbers):
    """이어붙여 만들 수 있는 가장 큰 수를 문자열로 반환한다.

    두 수 a, b 의 순서는 a+b 와 b+a 를 문자열로 비교해 큰 쪽으로 정한다.
    "어느 쪽이 큰 자리부터 채우나" 는 원소 하나만 봐서는 알 수 없고 두 원소를
    같이 놓아야 정해지므로, key 가 아니라 cmp_to_key 로 쌍 비교를 넘긴다.
    문자열 변환은 정렬 전에 한 번만 해 둔다 (비교마다 다시 만들지 않는다).

    Args:
        numbers (list[int]): 0 이상 1,000 이하의 정수 리스트.

    Returns:
        str: 이어붙여 만들 수 있는 가장 큰 수. 전부 0 이면 "0".
    """
    strings = list(map(str, numbers))
    strings.sort(key=cmp_to_key(lambda a, b: (a + b < b + a) - (a + b > b + a)))
    answer = ''.join(strings)
    return '0' if answer[0] == '0' else answer


# --- 설명 ---
#
# 고친 곳 둘.
# ① 문자열 변환을 정렬 전에 한 번만 한다. 원래는 compare 가 불릴 때마다
#    map(str, [a,b]) 를 새로 만들었는데, 비교는 O(n log n) 번 일어나므로 그만큼
#    반복된다. 정렬 대상 자체를 문자열로 바꿔 두면 비교 안은 a + b 로 끝난다.
# ② str(0) → '0'. str(0) 은 그냥 '0' 이라 굳이 함수를 부를 이유가 없다.
# 시간복잡도: 비교마다 문자열을 이어붙이므로 O(n log n · k) (k = 자릿수).
# 공간복잡도: 문자열 리스트와 결과 문자열로 O(n · k).
#
# 더 나은 표현 — cmp_to_key 없이도 된다:
#   ''.join(sorted(map(str, numbers), key=lambda x: x * 3, reverse=True))
# 원소를 3번 반복한 것을 키로 쓰면("3"→"333", "30"→"303030") 앞에서부터 사전순
# 비교가 곧 이어붙였을 때의 대소가 된다. 제한이 1,000 이하(최대 4자리)라 3번이면
# 충분한지 0~1000 의 모든 쌍을 직접 돌려 확인했다 — 틀리는 쌍 0개.
# 다만 x * 2 로 줄이면 45쌍이 틀린다(('3','330') 등). 반복 횟수는 "가장 긴 원소
# 길이" 에 기대는 값이라, 제한이 바뀌면 같이 봐야 한다.
#
# 짧지만 안 되는 대안:
#   ''.join(sorted(map(str, numbers), reverse=True))   # 단순 문자열 내림차순
#   → [3, 30] 에서 "303" (정답 "330"). 사전순으로는 "30" > "3" 이라 30 을 앞에
#     놓는데, 이어붙이면 330 > 303 이다. 처음 접근한 "앞자리 큰 순" 직관이 정확히
#     여기서 갈린다.
#   ''.join(map(str, sorted(numbers, reverse=True)))   # 숫자 내림차순
#   → [6, 10, 2] 에서 "1062". 값의 크기와 이어붙인 결과의 크기는 다른 축이다.
#
# 다시 만나면: "순서를 정해서 이어붙인 결과를 최대/최소로" 류는 원소 하나의
# 크기가 아니라 **두 원소를 이어붙인 두 가지 결과를 비교**하는 규칙을 먼저 세운다.
# 그 규칙이 원소 하나의 key 로 안 떨어지면 functools.cmp_to_key 로 쌍 비교를 넘긴다.
