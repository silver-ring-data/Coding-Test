def solution(array, commands):
    """각 command로 지정된 구간을 잘라 정렬한 뒤 k번째 값을 뽑아 반환한다.

    Args:
        array (list[int]): 원본 배열.
        commands (list[list[int]]): [i, j, k] 형태. array의 i번째부터 j번째까지
            (1-indexed, 양끝 포함) 자른 뒤 오름차순 정렬했을 때 k번째(1-indexed)
            값을 구하라는 뜻이다.

    Returns:
        list[int]: 각 command에 대한 답을 순서대로 담은 리스트.
    """
    answer = []
    for command in commands:
        i, j, k = command[0] - 1, command[1], command[2] - 1
        answer.append(sorted(array[i:j])[k])

    return answer


# --- 피드백 과정 ---
#
# 처음엔 정렬을 통째로 빼먹고 array[i:j][k]만 썼다. 정렬을 넣은 다음에도
# i,j에 +1,+2를 잘못 더해(command[0]+1, command[1]+2) 슬라이스가 뒤로 밀리면서
# IndexError가 났다 — array=[1,5,2,6,3,7,4], command=[2,5,3] 예제를 손으로
# 따라가며 i,j,k 값과 슬라이스 결과를 하나씩 짚어보고서야 올바른 식(i-1, j 그대로,
# k-1)을 찾았다.
#
# --- 설명 ---
#
# 1-indexed 구간 [i, j]를 파이썬 슬라이스로 옮기는 게 핵심이었다 — 시작은 i-1,
# 끝은 j를 그대로 쓴다(슬라이스는 끝 인덱스를 포함하지 않으므로, j번째 원소까지
# 넣으려면 끝을 j로 둬야 한다). k번째 값은 정렬 후 인덱스 k-1.
# 시간복잡도: O(len(commands) * m log m) (m = 자른 구간 길이). 배열·명령 개수가
# 문제 제약상 작아 이 이상 최적화할 필요는 없다.
# 짧지만 안 되는 대안: array[i-1:j-1]처럼 끝도 -1 하는 것 — "j번째까지 포함"을
# "j-1번째까지"로 착각하기 쉬운데, 슬라이스의 끝은 이미 미포함이라 j를 그대로
# 써야 j번째 원소가 들어온다.
#
# 다시 만나면: 1-indexed 구간을 슬라이스로 옮길 땐 시작만 -1, 끝은 그대로 —
# 끝을 건드리면 슬라이스의 "끝 미포함" 규칙과 두 번 겹쳐 계산하게 된다.
