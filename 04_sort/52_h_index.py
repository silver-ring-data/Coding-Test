def solution(citations):
    """논문별 인용 수를 받아 H-Index를 계산해 반환한다.

    인용 수를 내림차순 정렬한 뒤, 1등부터 순위를 매겨 "순위 <= 인용수"가
    유지되는 가장 큰 순위를 h로 본다. 논문 h편이 h번 이상 인용됐고
    나머지는 h번 이하 인용됐다는 H-Index 정의와 이 순위 비교가 같은 말이기 때문이다.

    Args:
        citations (list[int]): 논문별 인용된 횟수.

    Returns:
        int: H-Index 값.
    """
    citations.sort(reverse=True)

    h = 0
    for rank, citation in enumerate(citations, start=1):
        if citation >= rank:
            h = rank
        else:
            break

    return h


# --- 피드백 과정 ---
#
# H-Index 정의 자체가 처음엔 안 와닿았다 — [3,0,6,1,5] 예제(정답 3)를 손으로
# 짚어보며 "인용 3번 이상인 논문이 3편, 나머지는 3번 이하"인 걸 확인하고서야
# 감이 왔다. 그 다음 "정렬 후 순위랑 인용수를 비교하면 h가 보인다"(내림차순
# [6,5,3,1,0]에서 순위 <= 인용수가 3등까지 유지)는 것도 힌트로 짚었다.
# 여기까지는 스스로 짚었는데, 이걸 `enumerate`로 순위를 뽑아 루프 안에서
# 비교하는 코드로 옮기는 단계에서 시간이 부족해 세션이 마무리했다.
#
# --- 설명 ---
#
# 정렬 후 순위(1부터)와 인용수를 나란히 비교하는 게 핵심이다. 오름차순으로
# 정렬한 뒤 "뒤에서부터" 세는 방법도 있지만, 문제를 "1등부터"로 이해했으므로
# 내림차순 정렬이 더 자연스럽다. 순위가 인용수를 넘어서는 순간 그 뒤로는
# 정렬돼 있어 절대 다시 성립하지 않으므로 break로 끝내도 된다(작은 입력이라
# 없어도 무방하지만 의미가 더 잘 드러난다).
# 시간복잡도: O(n log n) (정렬이 지배적, 순위 비교는 O(n)).
# 짧지만 안 되는 대안: 인용수를 그대로 두고 "citations[i] >= i" 처럼 0-indexed로
# 비교하는 것 — 순위는 1등부터 세는 개념이라 인덱스(0부터)를 그대로 쓰면 한 칸씩 밀린다.
#
# 다시 만나면: "정렬된 값과 순위(위치)를 맞대어 비교"하는 유형이면 정렬 방향부터
# 정하고(1등이 앞이냐 뒤냐), enumerate(..., start=1)로 순위를 자연스럽게 얻는다.
